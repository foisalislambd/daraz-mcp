function epis(
  name: string,
  path: string,
  method: HttpMethod,
): ApiEndpoint {
  return {
    name,
    group: "logistics-partner",
    path,
    method,
    write: method === "POST",
    description:
      "Logistics partner (EPIS) API from the portal Logistics section. Not a normal seller-centre call.",
    verification: "official-portal-capture",
    sellerTool: false,
  };
}

